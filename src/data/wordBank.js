const recommendedTerms = ["強顏歡笑", "欲言又止", "寂寥", "月白風清", "由此可見", "值得注意的是", "眼眶泛紅", "沉鬱"];

export function fuzzySearch(query, source = wordBank) {
  const normalizedQuery = normalizeText(query);

  if (!normalizedQuery) {
    return source
      .map((item) => ({
        ...item,
        score: recommendedTerms.includes(item.term) ? 20 : 1,
      }))
      .sort((a, b) => b.score - a.score || a.term.localeCompare(b.term, "zh-Hant"))
      .slice(0, 12);
  }

  const tokens = normalizedQuery.split(/[\s,，、。；;]+/).filter(Boolean);
  const queryChars = [...new Set([...normalizedQuery].filter((char) => !/\s/.test(char)))];

  return source
    .map((item) => {
      const fields = [
        { value: item.term, weight: 18 },
        { value: item.type, weight: 8 },
        { value: item.meaning, weight: 9 },
        { value: item.keywords.join(" "), weight: 14 },
        { value: item.tone.join(" "), weight: 12 },
        { value: item.example, weight: 4 },
      ];

      const score = fields.reduce((total, field) => {
        const value = normalizeText(field.value);
        const tokenScore = tokens.reduce((sum, token) => {
          if (value.includes(token)) return sum + field.weight * (token === normalizeText(item.term) ? 3 : 2);
          const overlap = [...token].filter((char) => value.includes(char)).length;
          return sum + (overlap / Math.max(token.length, 1)) * field.weight;
        }, 0);
        return total + tokenScore;
      }, 0);

      const characterScore = queryChars.reduce((sum, char) => {
        const fieldsText = normalizeText(`${item.term} ${item.meaning} ${item.keywords.join(" ")} ${item.tone.join(" ")}`);
        return sum + (fieldsText.includes(char) ? 0.65 : 0);
      }, 0);

      return {
        ...item,
        score: score + characterScore,
      };
    })
    .filter((item) => item.score >= 2)
    .sort((a, b) => b.score - a.score || a.term.localeCompare(b.term, "zh-Hant"))
    .slice(0, 24);
}

function normalizeText(value = "") {
  return String(value).trim().toLowerCase();
}
